def site_label(site_key: str) -> str:
    if site_key in SITE_BY_KEY:
        return SITE_BY_KEY[site_key].name
    if site_key.startswith("custom:"):
        return site_key.split(":", 1)[1]
    return site_key


def site_icon_domain(site_key: str) -> str:
    if site_key in SITE_BY_KEY:
        return SITE_BY_KEY[site_key].icon_domain
    return site_key.split(":", 1)[1] if site_key.startswith("custom:") else ""


# ---------- формат cookies.txt (Netscape) ----------
def cookies_to_netscape(cookies: list[dict]) -> str:
    lines = ["# Netscape HTTP Cookie File", "# Generated by Zephyrus", ""]
    for c in cookies:
        domain = c.get("domain", "")
        if not domain:
            continue
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        prefix = "#HttpOnly_" if c.get("httponly") else ""
        lines.append("\t".join([
            prefix + domain, include_sub, c.get("path") or "/",
            "TRUE" if c.get("secure") else "FALSE", str(int(c.get("expires") or 0)),
            c.get("name", ""), c.get("value", ""),
        ]))
    return "\n".join(lines) + "\n"


def parse_netscape(text: str) -> list[dict]:
    cookies: list[dict] = []
    for raw in text.splitlines():
        line = raw.strip("\r\n")
        if not line.strip():
            continue
        httponly = False
        if line.startswith("#HttpOnly_"):
            httponly = True
            line = line[len("#HttpOnly_"):]
        elif line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 7:
            continue
        domain, _sub, path, secure, expires, name, value = parts
        try:
            exp = int(float(expires))
        except ValueError:
            exp = 0
        cookies.append({"domain": domain, "path": path or "/", "secure": secure.upper() == "TRUE",
                        "httponly": httponly, "expires": exp, "name": name, "value": value})
    return cookies


class SessionManager(QObject):
    changed = pyqtSignal()

    def __init__(self, db: Database, vault: Vault) -> None:
        super().__init__()
        self._db = db
        self._vault = vault

    # ---------- чтение ----------
    def profiles(self, site: str | None = None) -> list[dict]:
        rows = self._db.list_profiles()
        out = [dict(r) for r in rows]
        return [p for p in out if site is None or p["site"] == site]

    def profile(self, pid: str) -> dict | None:
        row = self._db.get_profile(pid)
        return dict(row) if row else None

    def profile_for_url(self, url: str) -> dict | None:
        """Активный профиль, чьи домены подходят к хосту ссылки."""
        host = host_of(url)
        if not host:
            return None
        for p in self.profiles():
            if not p["active"]:
                continue
            for h in filter(None, p["hosts"].split(",")):
                if host == h or host.endswith("." + h):
                    return p
        return None

    # ---------- запись ----------
    def _path(self, pid: str) -> Path:
        return PROFILES_DIR / f"{pid}.zcp"

    def add_profile(self, site: str, name: str, cookies: list[dict], hosts: list[str] | None = None) -> str:
        pid = uuid.uuid4().hex
        payload = json.dumps(cookies, ensure_ascii=False).encode("utf-8")
        self._path(pid).write_bytes(self._vault.encrypt(payload))
        if hosts is None:
            if site in SITE_BY_KEY:
                hosts = list(SITE_BY_KEY[site].domains)
            else:
                hosts = [site.split(":", 1)[1]] if ":" in site else []
        self._db.insert_profile(pid, site, name, hosts, len(cookies))
        self.changed.emit()
        return pid

    def load_cookies(self, pid: str) -> list[dict]:
        data = self._vault.decrypt(self._path(pid).read_bytes())
        return json.loads(data.decode("utf-8"))

    def rename(self, pid: str, name: str) -> None:
        self._db.rename_profile(pid, name)
        self.changed.emit()

    def set_active(self, pid: str) -> None:
        self._db.set_active_profile(pid)
        self.changed.emit()

    def delete(self, pid: str) -> None:
        self._db.delete_profile(pid)
        try:
            self._path(pid).unlink(missing_ok=True)
        except OSError:
            pass
        self.changed.emit()

    def import_netscape_file(self, site: str, name: str, file_path: str) -> str:
        text = Path(file_path).read_text(encoding="utf-8", errors="replace")
        cookies = parse_netscape(text)
        if not cookies:
            raise ValueError("В файле не найдено ни одной cookie в формате Netscape")
        return self.add_profile(site, name, cookies)

    def export_temp_cookiefile(self, pid: str, target: Path) -> Path:
        """Расшифровать профиль во временный cookies.txt для yt-dlp (удаляется после загрузки)."""
        target.write_text(cookies_to_netscape(self.load_cookies(pid)), encoding="utf-8")
        return target

    @staticmethod
    def custom_site_key(url: str) -> tuple[str, list[str]]:
        base = base_domain(host_of(url))
        return f"custom:{base}", [base]
